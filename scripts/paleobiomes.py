#!/usr/bin/env python3
"""Regenerate the globe's vegetation layers (#54) from Beyer, Krapp & Manica (2020), "High-resolution terrestrial
climate, bioclimate and vegetation for the last 120,000 years", Scientific Data 7, 236 (doi:10.1038/s41597-020-0552-1);
data doi:10.6084/m9.figshare.12293345 (CC BY 4.0): BIOME4 biomes driven by bias-corrected HadCM3 climate, 0.5°,
every 2,000 years from 120 ka and every 1,000 years over the last 22 ka. MODELLED.

    python3 -m pip install h5py numpy
    python3 scripts/paleobiomes.py LateQuaternary_Environment.nc   (the 1.3 GB file from the figshare record)

→ public/paleo/biome-<years ago>.png: 720×360 8-bit grey, equirectangular, north up, longitude −180 at the left;
  0 = no land data (water, or south of 60° S), otherwise BIOME4 class + 1.
→ src/data/paleo-biomes.js: the slice times, class names (from the file) and the colours the globe paints them.
"""
import sys, os, zlib, struct, json
import h5py, numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
# natural land-cover colours: forests dark green, savannas and grasslands olive to straw, deserts sand, tundra grey-brown, ice white
COLOURS = {0: None, 1: '#1f5a28', 2: '#2b6430', 3: '#4c7534', 4: '#3b6a34', 5: '#2e573a', 6: '#3f6834', 7: '#395d37', 8: '#2f5038',
           9: '#3a573d', 10: '#33503b', 11: '#4a5c3f', 12: '#8c9046', 13: '#a08f56', 14: '#9b8a63', 15: '#6d7944', 16: '#7e894b',
           17: '#5e6d47', 18: '#69724f', 19: '#a69c56', 20: '#9ea063', 21: '#cdb68b', 22: '#a49d7d', 23: '#88876d', 24: '#908b73',
           25: '#988f7b', 26: '#a29b89', 27: '#9f978d', 28: '#e0e7ed'}

def png(w, h, grey):
    raw = b''.join(b'\x00' + grey[y].tobytes() for y in range(h))
    chunk = lambda t, d: struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 0, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b'')

f = h5py.File(sys.argv[1], 'r')
lat, lon, times = f['latitude'][:], f['longitude'][:], f['time'][:]
assert len(lon) == 720 and abs(lon[0] + 179.75) < 1e-3 and abs(lat[0] + 59.75) < 1e-3 and abs(lat[-1] - 89.75) < 1e-3
attrs = f['biome'].attrs
names = {int(k.split('_')[1]): attrs[k].decode() for k in attrs if k.startswith('biome_')}
out = os.path.join(ROOT, 'public', 'paleo'); os.makedirs(out, exist_ok=True)
total = 0
for i, t in enumerate(times):
    b = f['biome'][i]                                  # (300 lat south→north, 720 lon)
    code = np.where(np.isfinite(b), np.nan_to_num(b) + 1, 0).astype(np.uint8)
    grid = np.zeros((360, 720), np.uint8)
    grid[0:300] = code[::-1]                           # north up: rows 0–299 are 89.75° N … 59.75° S
    data = png(720, 360, grid)
    with open(os.path.join(out, f'biome-{-int(t)}.png'), 'wb') as fh: fh.write(data)
    total += len(data)
js = ('// GENERATED by scripts/paleobiomes.py from Beyer, Krapp & Manica 2020 (Sci. Data 7, 236; data CC BY 4.0, doi:10.6084/m9.figshare.12293345):\n'
      '// BIOME4 biomes from bias-corrected HadCM3 climate. MODELLED. Do not edit.\n'
      f'export const BIOME_YEARS = {json.dumps(sorted(-int(t) for t in times))}; // years ago, one public/paleo/biome-<years>.png each\n'
      f'export const BIOME_NAMES = {json.dumps([names[k] for k in sorted(names)], ensure_ascii=False)}; // BIOME4 class 0…28 (PNG value − 1)\n'
      f'export const BIOME_COLOURS = {json.dumps([COLOURS[k] for k in sorted(names)])};\n')
with open(os.path.join(ROOT, 'src', 'data', 'paleo-biomes.js'), 'w') as fh: fh.write(js)
print(f'{len(times)} slices, {total / 1024:.0f} KB; classes {len(names)}')
