#!/usr/bin/env node
// Calibrate each moon's orbital phase against JPL Horizons.
//
// JPL's mean elements give the orbit's shape and orientation well, but their rounded periods
// drift by whole revolutions over decades. This fits the mean longitude (at FIT_JD) and the
// mean motion to Horizons positions sampled from 2016 to 2036, keeping JPL's geometry and
// precession, and writes src/data/moon-fit.js. Re-run when updating src/data/moons.js:
//   node scripts/fit-moons.js

import fs from 'node:fs/promises';
import path from 'node:path';
import { MOONS } from '../src/data/moons.js';
import { moonFromElements } from '../src/astro/moons.js';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const FIT_JD = 2461041.5; // 2026-01-01
const PARENT = { mars: 499, jupiter: 599, saturn: 699, uranus: 799, neptune: 899, pluto: 999 };
const HORIZONS_ID = { phobos: 401, deimos: 402, io: 501, europa: 502, ganymede: 503, callisto: 504, amalthea: 505,
  mimas: 601, enceladus: 602, tethys: 603, dione: 604, rhea: 605, titan: 606, hyperion: 607, iapetus: 608, phoebe: 609,
  miranda: 705, ariel: 701, umbriel: 702, titania: 703, oberon: 704, triton: 801, proteus: 808, nereid: 802, charon: 901 };

const unit = (v) => { const l = Math.hypot(...v); return v.map((x) => x / l); };
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const wrap = (d) => ((d % 360) + 540) % 360 - 180;

async function vectors(id, parent, jds) {
  const params = new URLSearchParams({ format: 'json', COMMAND: `'${id}'`, OBJ_DATA: 'NO', EPHEM_TYPE: 'VECTORS',
    CENTER: `'500@${parent}'`, REF_PLANE: 'ECLIPTIC', REF_SYSTEM: 'ICRF', VEC_TABLE: '1', OUT_UNITS: 'KM-S', CSV_FORMAT: 'YES',
    TLIST: jds.map((j) => `'${j}'`).join(' ') });
  const res = await fetch(`https://ssd.jpl.nasa.gov/api/horizons.api?${params}`);
  const r = (await res.json()).result;
  return r.slice(r.indexOf('$$SOE') + 5, r.indexOf('$$EOE')).trim().split('\n')
    .map((l) => l.split(',').map((s) => s.trim())).map((c) => [Number(c[0]), [Number(c[2]), Number(c[3]), Number(c[4])]]);
}

/** Mean longitude that puts the model closest (in direction) to `obs` at `jd`. */
function observedLambda(el, jd, obs) {
  const u = unit(obs);
  const score = (L) => dot(unit(moonFromElements({ ...el, fit: { jd, lambda: L, n: 0 } }, jd)), u);
  let best = 0, bs = -2;
  for (let L = 0; L < 360; L += 1) { const s = score(L); if (s > bs) { bs = s; best = L; } }
  for (let step = 0.5; step > 1e-5; step /= 2) for (const d of [-step, step]) { const s = score(best + d); if (s > bs) { bs = s; best += d; } }
  return best;
}

const out = {};
for (const m of MOONS) {
  const hid = HORIZONS_ID[m.id];
  if (!hid) continue;
  const P = m.elements.P;
  // progressively longer baselines so revolutions can be counted without ambiguity
  const offsets = [0, P / 8, P / 4, P / 2, P, 3 * P, 10 * P, 30 * P, 100 * P, 300 * P, 1000 * P, 3000 * P, 10000 * P, 30000 * P]
    .filter((d) => d <= 3653);
  const jds = [...new Set([...offsets.map((d) => FIT_JD + d), ...offsets.slice(1).map((d) => FIT_JD - d)].map((j) => +j.toFixed(5)))].sort((a, b) => Math.abs(a - FIT_JD) - Math.abs(b - FIT_JD));
  const obs = new Map((await vectors(hid, PARENT[m.parent], jds)).map(([jd, v]) => [+jd.toFixed(5), v]));
  let n = 360 / P, L0 = observedLambda(m.elements, FIT_JD, obs.get(FIT_JD));
  const pts = [[0, L0]];
  for (const jd of jds.slice(1)) {
    const t = jd - FIT_JD, Lobs = observedLambda(m.elements, jd, obs.get(jd));
    const pred = L0 + n * t;
    pts.push([t, pred + wrap(Lobs - pred)]);
    // least squares through all points so far
    const k = pts.length, st = pts.reduce((s, p) => s + p[0], 0), sl = pts.reduce((s, p) => s + p[1], 0);
    const stt = pts.reduce((s, p) => s + p[0] * p[0], 0), stl = pts.reduce((s, p) => s + p[0] * p[1], 0);
    if (k > 2) { n = (k * stl - st * sl) / (k * stt - st * st); L0 = (sl - n * st) / k; }
  }
  const rms = Math.sqrt(pts.reduce((s, [t, L]) => s + wrap(L - (L0 + n * t)) ** 2, 0) / pts.length);
  out[m.id] = { jd: FIT_JD, lambda: +((L0 % 360 + 360) % 360).toFixed(4), n: +n.toFixed(9), rmsDeg: +rms.toFixed(3), samples: pts.length };
  console.log(m.id.padEnd(10), out[m.id]);
}
const body = Object.entries(out).map(([id, f]) => `  ${id}: ${JSON.stringify(f)},`).join('\n');
await fs.writeFile(path.join(root, 'src/data/moon-fit.js'), `// Generated by scripts/fit-moons.js on ${new Date().toISOString().slice(0, 10)}: each moon's mean longitude (deg at jd)
// and mean motion (deg/day) fitted to JPL Horizons positions 2016–2036; rmsDeg = scatter of the fit.
export const MOON_FIT = {
${body}
};
`);
