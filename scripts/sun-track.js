// Regenerate src/data/sun-track.js (#53): the Sun's evolutionary track from MIST v1.2 (Choi et al. 2016;
// Dotter 2016), 1.00 M☉, [Fe/H] = 0, non-rotating, from the pre-main sequence to the white-dwarf cooling track.
//   node scripts/sun-track.js            (downloads the 100 MB solar-metallicity EEP tarball once)
//   node scripts/sun-track.js <file.eep> (an already extracted 00100M.track.eep)
// Kept: age (yr), mass (M☉), log L (L☉), log T_eff (K), log R (R☉), MIST phase. Points are thinned where the
// track barely moves, and every phase boundary is kept.

import fs from 'node:fs/promises';
import { spawn } from 'node:child_process';

const TAR = 'https://mist.science/data/tarballs_v1.2/MIST_v1.2_feh_p0.00_afe_p0.0_vvcrit0.0_EEPS.txz';
const MEMBER = 'MIST_v1.2_feh_p0.00_afe_p0.0_vvcrit0.0_EEPS/00100M.track.eep';

async function eepText() {
  if (process.argv[2]) return fs.readFile(process.argv[2], 'utf8');
  const res = await fetch(TAR, { signal: AbortSignal.timeout(900000) });
  if (!res.ok) throw new Error(`MIST HTTP ${res.status}`);
  const tar = spawn('tar', ['-xJOf', '-', MEMBER]);
  let out = '';
  tar.stdout.on('data', (d) => { out += d; });
  const done = new Promise((ok, fail) => tar.on('close', (c) => (c ? fail(new Error(`tar exit ${c}`)) : ok())));
  for await (const chunk of res.body) if (!tar.stdin.write(chunk)) await new Promise((r) => tar.stdin.once('drain', r));
  tar.stdin.end();
  await done;
  return out;
}

const text = await eepText();
const head = text.split('\n').find((l) => /^#\s+star_age/.test(l)).replace(/^#/, '').trim().split(/\s+/);
const col = (n) => head.indexOf(n);
const C = { age: col('star_age'), mass: col('star_mass'), L: col('log_L'), T: col('log_Teff'), R: col('log_R'), phase: col('phase') };
const all = text.split('\n').filter((l) => l.trim() && !l.startsWith('#')).map((l) => l.trim().split(/\s+/).map(Number))
  .map((f) => [f[C.age], f[C.mass], f[C.L], f[C.T], f[C.R], f[C.phase]]);
// thin: keep a point when the track has moved 0.01 dex in L or T, the phase changes, or it is first/last
const kept = [];
for (const p of all) {
  const q = kept.at(-1);
  if (!q || p[5] !== q[5] || Math.abs(p[2] - q[2]) > 0.01 || Math.abs(p[3] - q[3]) > 0.002 || p === all.at(-1)) kept.push(p);
}
const rows = kept.map(([a, m, L, T, R, ph]) => [Number(a.toPrecision(6)), +m.toFixed(4), +L.toFixed(3), +T.toFixed(4), +R.toFixed(3), ph]);
const js = `// GENERATED by scripts/sun-track.js from MIST v1.2 (Choi et al. 2016, ApJ 823, 102; Dotter 2016), 1.00 M☉, [Fe/H] = 0,
// v/v_crit = 0. Rows: [age yr, mass M☉, log L/L☉, log T_eff K, log R/R☉, phase]. Phases: −1 pre-main sequence, 0 main
// sequence, 2 red-giant branch, 3 core helium burning, 4 early AGB, 5 thermally pulsing AGB, 6 post-AGB, 9 white dwarf.
// ${all.length} model points thinned to ${rows.length}. Do not edit.
export default ${JSON.stringify(rows)};
`;
await fs.writeFile(new URL('../src/data/sun-track.js', import.meta.url), js);
console.log(`wrote ${rows.length} of ${all.length} points (${(js.length / 1024).toFixed(0)} KB)`);
