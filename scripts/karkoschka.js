#!/usr/bin/env node
// Bundle the measured full-disc albedo spectra of Jupiter, Saturn, Uranus, Neptune and Titan
// (Karkoschka 1998, Icarus 133, 134, doi:10.1006/icar.1998.5913; ESO July 1995, 300–1050 nm,
// 1 nm resolution) from the NASA PDS Atmospheres Node (data set ESO-J/S/N/U-SPECTROPHOTOMETER-4-V2.0,
// doi:10.17189/2bp8-k793) into src/data/reflectance-karkoschka.js for the spectrum filter (#28, #61):
// 0.4 nm samples averaged into 2 nm bins, albedo to 4 decimals.
import fs from 'node:fs/promises';

const URL_TAB = 'https://atmos.nmsu.edu/pdsd/archive/data/eso-jsnu-spectrophotometer-4-v20/gbat_0001/data/1995low.tab';
const src = process.argv[2] ? await fs.readFile(process.argv[2], 'utf8') : await (await fetch(URL_TAB)).text();
const rows = src.trim().split('\n').map((l) => l.trim().split(/\s+/).map(Number)).filter((r) => r.length >= 8 && Number.isFinite(r[0]));
const BODIES = ['jupiter', 'saturn', 'uranus', 'neptune', 'titan']; // columns 4–8 (vacuum wavelength in column 1)
const bins = new Map();
for (const r of rows) {
  const b = Math.round(r[0] / 2) * 2;
  if (!bins.has(b)) bins.set(b, { n: 0, s: [0, 0, 0, 0, 0] });
  const e = bins.get(b); e.n++;
  for (let i = 0; i < 5; i++) e.s[i] += r[3 + i];
}
const out = { source: 'Karkoschka 1998, Icarus 133, 134 (doi:10.1006/icar.1998.5913): ESO full-disc albedo, July 1995, at the small phase angles seen from Earth', data: 'NASA PDS Atmospheres Node, ESO-J/S/N/U-SPECTROPHOTOMETER-4-V2.0 (doi:10.17189/2bp8-k793), 1995low.tab', spectra: {} };
for (const [i, id] of BODIES.entries()) out.spectra[id] = [...bins.entries()].sort((a, b) => a[0] - b[0]).map(([nm, e]) => [nm, +(e.s[i] / e.n).toFixed(4)]);
await fs.writeFile(new URL('../src/data/reflectance-karkoschka.js', import.meta.url), `// Generated by scripts/karkoschka.js — do not edit.\nexport default ${JSON.stringify(out)};\n`);
console.log(`${rows.length} rows → ${out.spectra.jupiter.length} bins, ${out.spectra.jupiter[0][0]}–${out.spectra.jupiter.at(-1)[0]} nm`);
