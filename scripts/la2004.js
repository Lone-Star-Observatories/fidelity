// Regenerate src/data/la2004.js (#54): Earth's orbital elements from the Laskar et al. (2004)
// solution, every 1,000 years from 2.7 Myr ago (the start of the Quaternary) to 1 Myr ahead.
//   node scripts/la2004.js
// Source: IMCCE, http://vo.imcce.fr/insola/earth/online/earth/La2004/ (INSOLN past, INSOLP future):
// columns t (kyr from J2000), eccentricity, obliquity (rad), longitude of perihelion from the moving
// equinox (rad, heliocentric). Stored as integers: e × 1e6, ε × 1e6 rad, ϖ × 1e5 rad (0…2π).

import fs from 'node:fs/promises';

const BASE = 'http://vo.imcce.fr/insola/earth/online/earth/La2004/';
const FROM = -2700, TO = 1000; // kyr

async function rows(file) {
  const res = await fetch(BASE + file, { signal: AbortSignal.timeout(120000) });
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  const out = new Map();
  for (const line of (await res.text()).split('\n')) {
    const f = line.trim().split(/\s+/).map((s) => Number(s.replace('D', 'E')));
    if (f.length === 4 && f.every(Number.isFinite)) out.set(Math.round(f[0]), f.slice(1));
  }
  return out;
}

const all = new Map([...(await rows('INSOLN.LA2004.BTL.ASC')), ...(await rows('INSOLP.LA2004.BTL.ASC'))]);
const e = [], eps = [], pi = [];
for (let t = FROM; t <= TO; t++) {
  const r = all.get(t);
  if (!r) throw new Error(`missing t = ${t} kyr`);
  e.push(Math.round(r[0] * 1e6));
  eps.push(Math.round(r[1] * 1e6));
  pi.push(Math.round((((r[2] % (2 * Math.PI)) + 2 * Math.PI) % (2 * Math.PI)) * 1e5));
}
const js = `// GENERATED by scripts/la2004.js from Laskar et al. (2004), A&A 428, 261 (IMCCE La2004 insolation files).
// Earth's eccentricity (×1e6), obliquity (rad ×1e6) and longitude of perihelion from the moving equinox
// (heliocentric, rad ×1e5), every 1 kyr from ${FROM} kyr to +${TO} kyr (t = 0 at J2000). Do not edit.
export default { from: ${FROM}, step: 1, e: [${e}], eps: [${eps}], pi: [${pi}] };
`;
await fs.writeFile(new URL('../src/data/la2004.js', import.meta.url), js);
console.log(`wrote ${e.length} rows (${(js.length / 1024).toFixed(0)} KB)`);
