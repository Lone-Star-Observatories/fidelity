// Regenerate the paleoclimate records and Mars' orbit for the Earth timeline (#54):
//   node scripts/paleo.js
// → src/data/paleo.js
//   LR04 benthic δ¹⁸O stack (Lisiecki & Raymo 2005), 0–3,000 ka, as published (1–5 kyr spacing).
//   Antarctic CO₂ composite, 0–800 ka (Bereiter et al. 2015, NOAA NCEI), averaged in 1-kyr bins.
//   Sea level, 0–798 ka (Spratt & Lisiecki 2016, "long PC1", with its 95% range), 1-kyr spacing.
// → src/data/la2004-mars.js
//   Mars' eccentricity, obliquity and longitude of perihelion from Laskar et al. (2004, Icarus 170, 343),
//   every 2 kyr from −5 Myr to +1 Myr (IMCCE). Integers: e × 1e6, ε × 1e6 rad, ϖ × 1e5 rad.

import fs from 'node:fs/promises';

const get = async (url) => {
  const res = await fetch(url, { signal: AbortSignal.timeout(120000), headers: { 'user-agent': 'USS-Fidelity data script' } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
};
const numRows = (text, minCols) => text.split(/\r?\n/).filter((l) => !l.startsWith('#')).map((l) => l.trim().split(/\s+/).map(Number))
  .filter((f) => f.length >= minCols && f.slice(0, minCols).every(Number.isFinite));

// LR04: "Time (ka)  d18O  error"
const lr04 = numRows(await get('https://lorraine-lisiecki.com/LR04stack.txt'), 3).filter((r) => r[0] <= 3000).map((r) => [r[0], r[1]]);
// Bereiter 2015: age (yr BP, gas), CO₂ ppm, 1σ → 1-kyr bin means
const bins = new Map();
for (const [age, ppm] of numRows(await get('https://www.ncei.noaa.gov/pub/data/paleo/icecore/antarctica/antarctica2015co2composite.txt'), 2)) {
  if (age < 500) continue; // the youngest samples overlap the industrial era, which the Keeling curve covers
  const k = Math.round(age / 1000), b = bins.get(k) ?? [0, 0];
  bins.set(k, [b[0] + ppm, b[1] + 1]);
}
const co2 = [...bins].sort((a, b) => a[0] - b[0]).map(([k, [s, n]]) => [k, +(s / n).toFixed(1)]);
// Spratt & Lisiecki 2016: age ka, short PC1 (+err), long PC1, σ, lo, up
// tab-separated with empty cells beyond 430 ka (where only the long PC1 continues)
const sea = (await get('https://www.ncei.noaa.gov/pub/data/paleo/contributions_by_author/spratt2016/spratt2016.txt')).split(/\r?\n/)
  .filter((l) => /^\d/.test(l)).map((l) => l.split('\t').map((c) => (c.trim() === '' ? NaN : Number(c))))
  .filter((f) => [0, 5, 7, 8].every((i) => Number.isFinite(f[i]))).map((f) => [f[0], +f[5].toFixed(1), +f[7].toFixed(1), +f[8].toFixed(1)]);

const paleo = `// GENERATED by scripts/paleo.js. Do not edit.
// LR04 benthic δ¹⁸O (‰), [ka, d18O]: Lisiecki & Raymo 2005, doi:10.1029/2004PA001071.
// Antarctic CO₂ (ppm), [ka, ppm], 1-kyr means: Bereiter et al. 2015, doi:10.1002/2014GL061957 (NOAA NCEI composite).
// Sea level (m relative to present), [ka, mean, 95% low, 95% high]: Spratt & Lisiecki 2016, doi:10.5194/cp-12-1079-2016.
export const LR04 = ${JSON.stringify(lr04)};
export const CO2 = ${JSON.stringify(co2)};
export const SEA_LEVEL = ${JSON.stringify(sea)};
`;
await fs.writeFile(new URL('../src/data/paleo.js', import.meta.url), paleo);
console.log(`paleo.js: LR04 ${lr04.length}, CO2 ${co2.length}, sea level ${sea.length} rows (${(paleo.length / 1024).toFixed(0)} KB)`);

// Mars
const MARS = 'https://ssp.imcce.fr/insola/earth/online/mars/La2003-04/';
const rows = new Map();
for (const f of ['INSOLN.LA2004.MARS.ASC', 'INSOLP.LA2004.MARS.ASC']) {
  for (const line of (await get(MARS + f)).split('\n')) {
    const v = line.trim().split(/\s+/).map((s) => Number(s.replace('D', 'E')));
    if (v.length === 4 && v.every(Number.isFinite)) rows.set(Math.round(v[0]), v.slice(1));
  }
}
const FROM = -5000, TO = 1000, STEP = 2, e = [], eps = [], pi = [];
for (let t = FROM; t <= TO; t += STEP) {
  const r = rows.get(t);
  if (!r) throw new Error(`Mars: missing t = ${t} kyr`);
  e.push(Math.round(r[0] * 1e6)); eps.push(Math.round(r[1] * 1e6));
  pi.push(Math.round((((r[2] % (2 * Math.PI)) + 2 * Math.PI) % (2 * Math.PI)) * 1e5));
}
const mars = `// GENERATED by scripts/paleo.js from Laskar et al. (2004), Icarus 170, 343 (IMCCE La2004 Mars). Do not edit.
// Mars' eccentricity (×1e6), obliquity (rad ×1e6), longitude of perihelion from the moving equinox (rad ×1e5),
// every ${STEP} kyr from ${FROM} kyr to +${TO} kyr (t = 0 at J2000).
export default { from: ${FROM}, step: ${STEP}, e: [${e}], eps: [${eps}], pi: [${pi}] };
`;
await fs.writeFile(new URL('../src/data/la2004-mars.js', import.meta.url), mars);
console.log(`la2004-mars.js: ${e.length} rows (${(mars.length / 1024).toFixed(0)} KB)`);
