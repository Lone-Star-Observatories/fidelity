#!/usr/bin/env node
// Bundle filter transmission curves (#28) from the SVO Filter Profile Service
// (http://svo2.cab.inta-csic.es/theory/fps/, Rodrigo & Solano) into src/data/filters.js:
// each curve resampled to ≤ 64 points, wavelength in nm, transmission normalised to a peak of 1.
import fs from 'node:fs/promises';

const IDS = {
  'johnson-U': 'Generic/Johnson.U', 'johnson-B': 'Generic/Johnson.B', 'johnson-V': 'Generic/Johnson.V', 'johnson-R': 'Generic/Johnson.R', 'johnson-I': 'Generic/Johnson.I',
  'sdss-u': 'SLOAN/SDSS.u', 'sdss-g': 'SLOAN/SDSS.g', 'sdss-r': 'SLOAN/SDSS.r', 'sdss-i': 'SLOAN/SDSS.i', 'sdss-z': 'SLOAN/SDSS.z',
  '2mass-J': '2MASS/2MASS.J', '2mass-H': '2MASS/2MASS.H', '2mass-Ks': '2MASS/2MASS.Ks',
  'wise-W1': 'WISE/WISE.W1', 'wise-W2': 'WISE/WISE.W2', 'wise-W3': 'WISE/WISE.W3', 'wise-W4': 'WISE/WISE.W4',
  'galex-FUV': 'GALEX/GALEX.FUV', 'galex-NUV': 'GALEX/GALEX.NUV',
  'uvot-UVW2': 'Swift/UVOT.UVW2', 'uvot-UVM2': 'Swift/UVOT.UVM2', 'uvot-UVW1': 'Swift/UVOT.UVW1',
  'wfc3-F225W': 'HST/WFC3_UVIS1.F225W', 'wfc3-F275W': 'HST/WFC3_UVIS1.F275W',
  'nircam-F200W': 'JWST/NIRCam.F200W', 'nircam-F444W': 'JWST/NIRCam.F444W', 'miri-F770W': 'JWST/MIRI.F770W', 'miri-F2100W': 'JWST/MIRI.F2100W',
};
const out = { source: 'SVO Filter Profile Service (Rodrigo et al. 2012, 2020; Rodrigo & Solano 2020)', url: 'http://svo2.cab.inta-csic.es/theory/fps/', filters: {} };
for (const [key, id] of Object.entries(IDS)) {
  const res = await fetch(`http://svo2.cab.inta-csic.es/theory/fps/getdata.php?format=ascii&id=${encodeURIComponent(id)}`);
  const rows = (await res.text()).trim().split('\n').map((l) => l.trim().split(/\s+/).map(Number)).filter((r) => r.length >= 2 && Number.isFinite(r[0]));
  if (rows.length < 3) { console.warn(`  ${id}: no data`); continue; }
  const peak = Math.max(...rows.map((r) => r[1]));
  const step = Math.max(1, Math.ceil(rows.length / 64));
  const pts = rows.filter((_, i) => i % step === 0 || i === rows.length - 1).map(([aa, t]) => [+(aa / 10).toFixed(2), +(t / peak).toFixed(4)]);
  out.filters[key] = { id, points: pts };
  console.log(`  ${key.padEnd(14)} ${id.padEnd(24)} ${pts.length} pts ${pts[0][0]}–${pts.at(-1)[0]} nm`);
}
await fs.writeFile(new URL('../src/data/filters.js', import.meta.url), `// Generated by scripts/filters.js — do not edit.\nexport default ${JSON.stringify(out)};\n`);
