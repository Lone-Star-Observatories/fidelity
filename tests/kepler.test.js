// Angular error as seen from the Sun, in degrees.
function angleDeg(a, b) {
  const dot = a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
  const n = Math.hypot(...a) * Math.hypot(...b);
  return (Math.acos(Math.min(1, dot / n)) * 180) / Math.PI;
}

// Standish quotes Table 1 errors up to ~15′ for Saturn and a few arcmin elsewhere;
// we allow 0.5° (30′) to stay robust at the ends of the valid range.
for (const [body, jd, ref] of REF) {
  test(`${body} @ JD ${jd} matches Horizons`, () => {
    const p = heliocentric(body, jd);
    const ang = angleDeg(p, ref);
    const dr = Math.abs(Math.hypot(...p) - Math.hypot(...ref)) / Math.hypot(...ref);
    assert.ok(ang < 0.5, `direction off by ${ang.toFixed(3)}°`);
    assert.ok(dr < 0.01, `distance off by ${(dr * 100).toFixed(2)}%`);
  });
}

test('Kepler solver converges for high eccentricity', () => {
  for (const e of [0, 0.2, 0.9, 0.99]) {
    for (let M = -3; M <= 3; M += 0.5) {
      const E = eccentricAnomaly(M, e);
      assert.ok(Math.abs(E - e * Math.sin(E) - M) < 1e-9);
    }
  }
});
